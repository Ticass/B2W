        // an ambient_calls argument: a string, a float, or None
        using Value = std::variant<std::monostate, std::string, double>;
        using Args = std::vector<Value>;

        bool IsStr(const Args& a, const size_t i)
        {
            return i < a.size() && std::holds_alternative<std::string>(a[i]);
        }

        const std::string& S(const Args& a, const size_t i)
        {
            return std::get<std::string>(a[i]);
        }

        bool AnyNone(const Args& a, const size_t from)
        {
            for (size_t i = from; i < a.size(); i++)
                if (std::holds_alternative<std::monostate>(a[i]))
                    return true;
            return false;
        }

        std::string Num(const double v)
        {
            char text[64];
            std::snprintf(text, sizeof text, "%.6g", v);
            return text;
        }

        // _csc_args
        std::string CscArgs(const Args& values)
        {
            std::string out;
            for (size_t i = 0; i < values.size(); i++)
            {
                if (i)
                    out += ", ";
                if (std::holds_alternative<std::string>(values[i]))
                    out += "\"" + std::get<std::string>(values[i]) + "\"";
                else if (std::holds_alternative<double>(values[i]))
                    out += Num(std::get<double>(values[i]));
                else
                    throw std::runtime_error("unsupported format string passed to NoneType.__format__");
            }
            return out;
        }

        // sounds.ambient_calls
        std::vector<std::pair<std::string, Args>> AmbientCalls(const std::string& source, const std::set<std::string>& names)
        {
            std::vector<std::pair<std::string, Args>> calls;
            const auto script = gsc::Parse(source, "<source amb>");
            const auto* main = script.Find("main");
            if (!main)
                return calls;
            const auto& tokens = script.tokens;
            for (size_t i = main->bodyOpen; i < main->bodyClose; i++)
            {
                const auto& token = tokens[i];
                if (!(token.kind == gsc::Kind::Ident && names.count(token.Low()) && tokens[i + 1].text == "(" && tokens[i - 1].text != "." && tokens[i - 1].text != "::"))
                    continue;
                std::vector<std::vector<const gsc::Token*>> args;
                std::vector<const gsc::Token*> current;
                int depth = 0;
                size_t j = i + 2;
                while (depth || tokens[j].text != ")")
                {
                    if (tokens[j].kind == gsc::Kind::Eof)
                        throw StepError("SoundError", "line " + std::to_string(token.line) + ": unterminated " + token.text + " call");
                    if (tokens[j].text == "(" || tokens[j].text == "[")
                        depth++;
                    else if (tokens[j].text == ")" || tokens[j].text == "]")
                        depth--;
                    if (!depth && tokens[j].text == ",")
                    {
                        args.push_back(current);
                        current.clear();
                    }
                    else
                        current.push_back(&tokens[j]);
                    j++;
                }
                if (!current.empty())
                    args.push_back(current);
                Args values;
                for (const auto& arg : args)
                {
                    if (arg.size() == 1 && arg[0]->kind == gsc::Kind::String)
                    {
                        values.emplace_back(arg[0]->text.substr(1, arg[0]->text.size() - 2));
                        continue;
                    }
                    std::string text;
                    for (const auto* t : arg)
                        text += t->text;
                    double v = 0;
                    if (py::ParseFloat(text, v))
                        values.emplace_back(v);
                    else
                        values.emplace_back(std::monostate{});
                }
                calls.emplace_back(token.Low(), std::move(values));
                i = j;
            }
            return calls;
        }

        double D(const Json& v)
        {
            return v.get<double>();
        }

        bool PatchSilent(const Json& p)
        {
            return D(p["room"]) <= -10000 || (D(p["reflections"]) <= -10000 && D(p["reverb"]) <= -10000);
        }

        std::vector<double> PatchFeatures(const Json& p)
        {
            return {std::log(std::max(D(p["decayTime"]), .1)), D(p["reflectionsDelay"]) * 10, D(p["roomHF"]) / 1000, (D(p["room"]) + D(p["reverb"])) / 1000};
        }

        std::string Upper(std::string s)
        {
            for (auto& c : s)
                if (c >= 'a' && c <= 'z')
                    c = static_cast<char>(c - 32);
            return s;
        }

        // sounds.radverb_for
        Json RadverbFor(const std::string& preset, const Json& globals)
        {
            std::vector<std::pair<std::string, Json>> patches;
            for (const auto& p : globals.value("reverbPatches", Json::array()))
                if (p.contains("name") && p["name"].is_string() && !p["name"].get<std::string>().empty())
                {
                    const auto key = Lower(p["name"].get<std::string>());
                    auto it = std::find_if(patches.begin(), patches.end(), [&](const auto& x) { return x.first == key; });
                    if (it == patches.end())
                        patches.emplace_back(key, p);
                    else
                        it->second = p;
                }
            const auto found = std::find_if(patches.begin(), patches.end(), [&](const auto& x) { return x.first == Lower(preset); });
            if (found == patches.end())
                return Json{{"status", "unknown_source_preset"}, {"source", preset}};
            const auto& patch = found->second;
            const auto patchName = patch["name"].get<std::string>();
            if (PatchSilent(patch))
                return Json{{"status", "silent_source_preset"}, {"source", patchName}, {"radverb", "default"}, {"wet", 0}};
            if (EAX_RADVERB.count(Upper(patchName)))
                return Json{{"status", "bo2_equivalent"}, {"source", patchName}, {"radverb", EAX_RADVERB.at(Upper(patchName))}};
            const Json* nearest = nullptr;
            double best = 0;
            const auto feature = PatchFeatures(patch);
            for (const auto& [_, p] : patches)
            {
                if (!EAX_RADVERB.count(Upper(p["name"].get<std::string>())))
                    continue;
                const auto other = PatchFeatures(p);
                double sum = 0;
                for (size_t k = 0; k < feature.size(); k++)
                    sum += (feature[k] - other[k]) * (feature[k] - other[k]);
                if (!nearest || sum < best || (sum == best && p["name"].get<std::string>() < (*nearest)["name"].get<std::string>()))
                    nearest = &p, best = sum;
            }
            if (!nearest)
                return Json{{"status", "unknown_source_preset"}, {"source", preset}};
            const auto nearestName = (*nearest)["name"].get<std::string>();
            return Json{{"status", "bo2_equivalent_nearest"}, {"source", patchName}, {"nearest", nearestName}, {"radverb", EAX_RADVERB.at(Upper(nearestName))}};
        }

        // repr() of a dict of strings
        std::string DictRepr(const Json& item)
        {
            std::string out = "{";
            bool first = true;
            for (const auto& [k, v] : item.items())
            {
                out += (first ? "" : ", ") + py::StringRepr(k) + ": " + py::StringRepr(v.get<std::string>());
                first = false;
            }
            return out + "}";
        }

        // sounds.port_music
        Json PortMusic(const std::string& source, const std::set<std::string>& aliases, std::vector<std::string>& lines)
        {
            Json report{{"states", Json::array()}, {"silent", Json::array()}, {"dropped", Json::array()}};
            std::optional<std::string> state;
            for (const auto& [name, args] : AmbientCalls(source, MUSIC_CALLS))
            {
                if (name == "declaremusicstate")
                {
                    if (!IsStr(args, 0))
                    {
                        report["dropped"].push_back(Json{{"call", name}, {"reason", "non-literal state"}});
                        state.reset();
                        continue;
                    }
                    state = S(args, 0);
                    report["states"].push_back(*state);
                    lines.push_back("declaremusicstate( \"" + *state + "\" );");
                }
                else if (!state)
                    report["dropped"].push_back(Json{{"call", name}, {"reason", "before any declared state"}});
                else if (name == "musicwaittilldone" || name == "musicwaittillstingerdone")
                    lines.push_back(name + "();");
                else
                {
                    if (!IsStr(args, 0) || AnyNone(args, 1))
                    {
                        report["dropped"].push_back(Json{{"call", name}, {"state", *state}, {"reason", "non-literal arguments"}});
                        continue;
                    }
                    auto alias = S(args, 0);
                    if (aliases.count(alias))
                        alias = "waw/" + alias;
                    else
                    {
                        report["silent"].push_back(Json{{"state", *state}, {"alias", alias}});
                        alias = "null";
                    }
                    Args out{alias};
                    out.insert(out.end(), args.begin() + 1, args.end());
                    lines.push_back(name + "( " + CscArgs(out) + " );");
                }
            }
            return report;
        }

        struct Room
        {
            Value radverb;
            Value dry, wet, fade;
        };

        // sounds.port_ambient
        Json PortAmbient(const std::string& source, const Json& globals, const std::set<std::string>& aliases, const std::set<std::string>& triggerRooms,
                         std::vector<std::string>& lines)
        {
            const auto calls = AmbientCalls(source, AMBIENT_CALLS);
            Json report{{"rooms", Json::object()}, {"packages", Json::array()}, {"dropped", Json::array()}, {"undeclared_trigger_rooms", Json::array()}};
            const auto lowest = [&](const std::string& kind) -> std::optional<std::string>
            {
                std::vector<const Args*> hits;
                for (const auto& [n, a] : calls)
                    if (n == kind && a.size() >= 2 && IsStr(a, 1))
                        hits.push_back(&a);
                const auto key = [](const Args* a) { return a->size() > 2 && std::holds_alternative<double>((*a)[2]) ? std::get<double>((*a)[2]) : 0.0; };
                std::stable_sort(hits.begin(), hits.end(), [&](const Args* x, const Args* y) { return key(x) < key(y); });
                return hits.empty() ? std::nullopt : std::optional(S(*hits[0], 1));
            };
            auto defaultRoom = lowest("activateambientroom");
            const auto defaultPackage = lowest("activateambientpackage");
            std::vector<std::pair<std::string, std::optional<Room>>> rooms;
            const auto findRoom = [&](const std::string& key) { return std::find_if(rooms.begin(), rooms.end(), [&](const auto& r) { return r.first == key; }); };
            std::set<std::string> packages;
            for (const auto& [name, args] : calls)
            {
                if (name == "activateambientroom" || name == "activateambientpackage")
                    continue;
                if (!IsStr(args, 0))
                {
                    report["dropped"].push_back(Json{{"call", name}, {"reason", "non-literal arguments"}});
                    continue;
                }
                const auto key = S(args, 0);
                if (name == "declareambientpackage")
                {
                    packages.insert(key);
                    lines.push_back("declareambientpackage( \"" + key + "\"" + (defaultPackage && key == *defaultPackage ? ", 1" : "") + " );");
                    report["packages"].push_back(key);
                }
                else if (name == "declareambientroom")
                {
                    if (findRoom(key) == rooms.end())
                        rooms.emplace_back(key, std::nullopt);
                    lines.push_back("declareambientroom( \"" + key + "\"" + (defaultRoom && key == *defaultRoom ? ", 1" : "") + " );");
                }
                else if (name == "addambientelement")
                {
                    if (!packages.count(key) || args.size() < 4 || !IsStr(args, 1) || AnyNone(args, 2))
                        report["dropped"].push_back(Json{{"call", name}, {"package", key}, {"reason", "undeclared package or arguments"}});
                    else if (!aliases.count(S(args, 1)))
                        report["dropped"].push_back(Json{{"call", name}, {"package", key}, {"alias", S(args, 1)}, {"reason", "alias not converted"}});
                    else
                    {
                        Args out{key, "waw/" + S(args, 1)};
                        out.insert(out.end(), args.begin() + 2, args.end());
                        lines.push_back("addambientelement( " + CscArgs(out) + " );");
                    }
                }
                else if (name == "setambientroomtone")
                {
                    if (findRoom(key) == rooms.end() || args.size() < 2 || !IsStr(args, 1) || AnyNone(args, 2))
                        report["dropped"].push_back(Json{{"call", name}, {"room", key}, {"reason", "undeclared room or arguments"}});
                    else if (!aliases.count(S(args, 1)))
                        report["dropped"].push_back(Json{{"call", name}, {"room", key}, {"alias", S(args, 1)}, {"reason", "alias not converted"}});
                    else
                    {
                        Args out{key, "waw/" + S(args, 1)};
                        out.insert(out.end(), args.begin() + 2, args.end());
                        lines.push_back("setambientroomtone( " + CscArgs(out) + " );");
                    }
                }
                else if (name == "setambientroomreverb")
                {
                    if (findRoom(key) == rooms.end() || args.size() < 4 || !IsStr(args, 1) || AnyNone(args, 2))
                    {
                        report["dropped"].push_back(Json{{"call", name}, {"room", key}, {"reason", "undeclared room or arguments"}});
                        continue;
                    }
                    auto mapping = RadverbFor(S(args, 1), globals);
                    if (!mapping.contains("radverb"))
                    {
                        mapping["radverb"] = "default";
                        mapping["wet"] = 0;
                    }
                    const double dry = std::get<double>(args[2]);
                    const double wet = mapping.contains("wet") && !mapping["wet"].is_null() ? 0.0 : std::get<double>(args[3]);
                    const double fade = args.size() > 4 ? std::get<double>(args[4]) : 2.0;
                    const auto radverb = mapping["radverb"].get<std::string>();
                    findRoom(key)->second = Room{radverb, dry, wet, fade};
                    mapping["dry"] = dry;
                    mapping["wet"] = wet;
                    report["rooms"][key] = mapping;
                    lines.push_back("setambientroomreverb( " + CscArgs({key, radverb, dry, wet, fade}) + " );");
                }
            }
            for (auto& [key, room] : rooms)
                if (!room)
                {
                    room = Room{std::string("default"), 1.0, 0.0, 2.0};
                    report["rooms"][key] = Json{{"status", "no_source_reverb"}, {"radverb", "default"}, {"dry", 1}, {"wet", 0}};
                    lines.push_back("setambientroomreverb( \"" + key + "\", \"default\", 1, 0 );");
                }
            if (!defaultRoom || findRoom(*defaultRoom) == rooms.end())
            {
                defaultRoom = "waw_default";
                rooms.emplace_back(*defaultRoom, Room{std::string("default"), 1.0, 0.0, 0.0});
                lines.insert(lines.begin(), "declareambientroom( \"waw_default\", 1 );\nsetambientroomreverb( \"waw_default\", \"default\", 1, 0, 0 );");
            }
            const auto def = *findRoom(*defaultRoom)->second;
            for (const auto& key : triggerRooms)
            {
                if (findRoom(key) != rooms.end())
                    continue;
                rooms.emplace_back(key, def);
                report["undeclared_trigger_rooms"].push_back(key);
                lines.push_back("declareambientroom( \"" + key + "\" );");
                lines.push_back("setambientroomreverb( " + CscArgs({key, def.radverb, def.dry, def.wet, def.fade}) + " );");
            }
            lines.push_back("setreverb( " + CscArgs({std::string("snd_enveffectsprio_level"), def.radverb, def.dry, def.wet, 0.0}) + " );");
            report["default_room"] = *defaultRoom;
            return report;
        }

        void ReplaceFirst(std::string& text, const std::string& from, const std::string& to)
        {
            const auto at = text.find(from);
            if (at != std::string::npos)
                text.replace(at, from.size(), to);
        }
