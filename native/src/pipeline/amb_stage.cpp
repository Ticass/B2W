    std::set<std::string> AmbientAliases(const std::string& source)
    {
        std::set<std::string> out;
        for (const auto& [name, args] : AmbientCalls(source, AMBIENT_CALLS))
            if ((name == "addambientelement" || name == "setambientroomtone") && args.size() > 1 && IsStr(args, 1))
                out.insert(S(args, 1));
        return out;
    }

    StepReport WriteAmbCsc(const std::string& project, const fs::path& projectRoot, const std::optional<fs::path>& sourceAmb,
                           const std::optional<fs::path>& ents)
    {
        const auto dst = projectRoot / "clientscripts" / "mp" / files::FromUtf8(project + "_amb.csc");
        fs::create_directories(dst.parent_path());
        const auto content = projectRoot / "content_source";
        const auto mix = sound::DefaultReverbMixOf(content);
        auto text = AMB_CSC;
        Json warnings = Json::array(), out = Json::object();
        const auto globalsPath = content / "sound_ir/driver_globals.json";
        if (sourceAmb && IsFile(globalsPath))
        {
            std::set<std::string> aliases;
            std::optional<fs::path> bank;
            std::error_code e;
            if (fs::is_directory(projectRoot / "soundbank", e))
                for (const auto& entry : fs::directory_iterator(projectRoot / "soundbank", e))
                {
                    const auto name = files::Utf8(entry.path().filename());
                    if (name.size() > 12 && Lower(name).substr(name.size() - 12) == ".aliases.csv")
                    {
                        bank = entry.path();
                        break;
                    }
                }
            if (bank)
            {
                const auto rows = ReadCsv(encoding::Utf8Replace(mod::Bytes(*bank)));
                if (!rows.empty())
                {
                    const auto column = std::find(rows[0].begin(), rows[0].end(), std::string("Name")) - rows[0].begin();
                    for (size_t i = 1; i < rows.size(); i++)
                        if (!rows[i].empty())
                        {
                            const auto& n = static_cast<size_t>(column) < rows[i].size() ? rows[i][column] : std::string();
                            aliases.insert(StartsWith(n, "waw/") ? n.substr(4) : n);
                        }
                }
            }
            std::set<std::string> triggerRooms;
            if (ents && IsFile(*ents))
            {
                static const pyre::Regex entity("\\{([^{}]*)\\}"), kv("\"([^\"]*)\"\\s+\"([^\"]*)\"");
                const auto entsText = encoding::WawText(mod::Bytes(*ents));
                for (const auto& body : entity.FindAll(entsText))
                {
                    std::map<std::string, std::string> fields;
                    for (const auto& pair : kv.FindAll(body[0]))
                        fields[pair[0]] = pair[1];
                    if (fields.count("targetname") && fields["targetname"] == "ambient_package" && fields.count("script_ambientroom") && !fields["script_ambientroom"].empty())
                        triggerRooms.insert(fields["script_ambientroom"]);
                }
            }
            const auto source = encoding::WawText(mod::Bytes(*sourceAmb));
            std::vector<std::string> ambientLines, musicLines;
            auto ambient = PortAmbient(source, mod::Json(globalsPath), aliases, triggerRooms, ambientLines);
            std::string body;
            for (const auto& block : ambientLines)
                for (const auto& line : py::Split(block, "\n"))
                    body += "    " + std::string(line) + "\n";
            auto music = PortMusic(source, aliases, musicLines);
            const auto ambName = files::Utf8(sourceAmb->filename());
            body += "    // WaW music states of " + ambName + ".\n";
            for (const auto& line : musicLines)
                body += "    " + line + "\n";
            for (const char* state : {"WAVE", "EGG", "SILENCE"})
                if (std::find(music["states"].begin(), music["states"].end(), Json(state)) != music["states"].end())
                    ReplaceFirst(text, std::string("    declaremusicstate( \"") + state + "\" );\n    musicalias( \"null\", 1 );\n", "");
            ReplaceFirst(text, "    declaremusicstate( \"WAVE\" );", "    // WaW rooms and packages of " + ambName + ".\n" + body + "    declaremusicstate( \"WAVE\" );");
            out["music_states"] = music;
            for (const auto& item : music["silent"])
                warnings.push_back("MUSIC_ALIAS_UNDEFINED " + item["state"].get<std::string>() + ": " + item["alias"].get<std::string>() +
                                   " is in no zone of the map (silent in WaW too); plays the null alias");
            for (const auto& item : music["dropped"])
                warnings.push_back("MUSIC_STATE_DROPPED " + DictRepr(item));
            Json ambientContent{{"source", Str(*sourceAmb)}};
            for (const auto& [k, v] : ambient.items())
                ambientContent[k] = v;
            out["ambient"] = ambientContent;
            for (const auto& [room, entry] : ambient["rooms"].items())
            {
                const auto status = entry["status"].get<std::string>();
                if (StartsWith(status, "bo2_equivalent"))
                    warnings.push_back("SOUND_ROOM_REVERB " + room + ": WaW I3DL2 " + entry["source"].get<std::string>() + " -> stock BO2 radverb " +
                                       entry["radverb"].get<std::string>() + (entry.contains("nearest") ? " (nearest " + entry["nearest"].get<std::string>() + ")" : ""));
                else if (status == "unknown_source_preset")
                    warnings.push_back("SOUND_ROOM_REVERB " + room + ": unknown WaW preset " + entry["source"].get<std::string>() + "; room kept dry");
            }
            for (const auto& item : ambient["dropped"])
                warnings.push_back("SOUND_AMBIENT_DROPPED " + DictRepr(item));
            if (!ambient["undeclared_trigger_rooms"].empty())
            {
                std::string names;
                for (const auto& n : ambient["undeclared_trigger_rooms"])
                    names += (names.empty() ? "" : ", ") + n.get<std::string>();
                warnings.push_back("SOUND_ROOM_UNDECLARED " + names + ": map triggers name no source room; given default room " + ambient["default_room"].get<std::string>());
            }
        }
        else if (mix["status"] == "silent_source_default")
            ReplaceFirst(text, "    declaremusicstate( \"WAVE\" );",
                         "    // WaW DEFAULT is silent; the BO2 DEFAULT radverb has reflections.\n"
                         "    declareambientroom( \"waw_default\", 1 );\n"
                         "    setambientroomreverb( \"waw_default\", \"default\", 1, 0, 0 );\n"
                         "    setreverb( \"snd_enveffectsprio_level\", \"default\", 1, 0, 0 );\n"
                         "    declaremusicstate( \"WAVE\" );");
        else
            warnings.push_back("SOUND_DEFAULT_REVERB " + mix["status"].get<std::string>() + ": source baseline not translated");
        out["default_reverb"] = mix;
        files::WriteText(dst, text);
        StepReport report;
        report.warnings = warnings.get<std::vector<std::string>>();
        for (auto& [section, value] : out.items())
            report.Add(section, std::move(value));
        return report;
    }
